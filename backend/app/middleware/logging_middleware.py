import logging
import time
import uuid

from starlette.middleware.base import BaseHTTPMiddleware, RequestResponseEndpoint
from starlette.requests import Request
from starlette.responses import Response

from app.middleware.error_handlers import internal_error_response

logger = logging.getLogger("app.requests")

REQUEST_ID_HEADER = "X-Request-ID"


class RequestLoggingMiddleware(BaseHTTPMiddleware):
    """Logs one line per request and gives every response an X-Request-ID.

    A user reporting a problem can quote the request id, which points to the exact log line
    (and, for crashes, the full traceback).
    """

    async def dispatch(self, request: Request, call_next: RequestResponseEndpoint) -> Response:
        # generated by the server, never taken from the client, so it cannot be forged into logs
        request_id = uuid.uuid4().hex
        request.state.request_id = request_id
        start = time.perf_counter()

        try:
            response = await call_next(request)
        except Exception:
            # an unexpected error: full traceback to the log, generic message to the client
            logger.exception(
                "Unhandled error in %s %s [%s]", request.method, request.url.path, request_id
            )
            response = internal_error_response()

        duration_ms = (time.perf_counter() - start) * 1000
        # only the path is logged, not the query string, which could contain tokens
        logger.info(
            "%s %s -> %d in %.1f ms [%s]",
            request.method,
            request.url.path,
            response.status_code,
            duration_ms,
            request_id,
        )
        response.headers[REQUEST_ID_HEADER] = request_id
        return response
